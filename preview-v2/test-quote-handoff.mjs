import assert from 'node:assert/strict';
await import('./quote-handoff-v3.js');
const q=globalThis.DUTRA_QUOTE_HANDOFF;
assert.ok(q,'quote handoff must attach');
const store=new Map();
const storage={setItem:(k,v)=>store.set(k,v),getItem:k=>store.get(k)||null,removeItem:k=>store.delete(k)};
const payload=q.payloadFromLead({id:'L1',empresa:'Transportadora Teste',cnpj:'12.345.678/0001-90',telefone:'44999999999',cidadeUf:'Maringá - PR'},{name:'Marcos',phone:'44988888888'},{installments:6,tier:'lead_ie',technical:{ruleId:'manual',vehicleName:'Pedido especial',qty:1,psi:120,totalTires:10,totalPieces:3,estimatedTotal:690,manualMode:true,note:'ajuste do cliente',lines:[{code:'EQ-120',name:'Equalizador 120',qty:2,unitPrice:220,manual:true},{code:'CUSTOM',name:'Peça especial',qty:1,unitPrice:250,manual:true}]},visuals:[{assetId:'asset-1',versionId:'version-1',category:'FLEET',title:'Pátio',usagePolicy:'PROPOSAL_ALLOWED',sensitivityLevel:'NORMAL',signedUrl:'https://should-not-persist.example/token'},{assetId:'asset-2',versionId:'version-2',category:'LOGO',title:'Logo',usagePolicy:'INTERNAL_REFERENCE',sensitivityLevel:'NORMAL'}]});
q.store(payload,storage);
const read=q.read(storage);
assert.equal(read.leadId,'L1');
assert.equal(read.client.company,'Transportadora Teste');
assert.equal(read.client.name,'Marcos');
assert.equal(read.commercial.installments,6);
assert.equal(read.commercial.tier,'lead_ie');
assert.equal(read.technical.manualMode,true);
assert.equal(read.technical.lines[0].unitPrice,220);
assert.equal(read.technical.lines[1].name,'Peça especial');
assert.equal(read.technical.note,'ajuste do cliente');
assert.equal(read.visuals.items.length,1);
assert.equal(read.visuals.items[0].assetId,'asset-1');
assert.equal(read.visuals.items[0].versionId,'version-1');
assert.equal(read.visuals.items[0].usagePolicy,'PROPOSAL_ALLOWED');
assert.equal(Object.hasOwn(read.visuals.items[0],'signedUrl'),false,'Signed URL nunca deve ser persistida no handoff');
q.clear(storage);
assert.equal(q.read(storage),null);
console.log('Quote handoff tests: PASS');